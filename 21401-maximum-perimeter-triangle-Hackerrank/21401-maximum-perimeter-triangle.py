def maximumPerimeterTriangle(sticks):
    sticks.sort(reverse=True)

    for i in range(len(sticks) - 2):
        a = sticks[i]
        b = sticks[i + 1]
        c = sticks[i + 2]

        # Triangle inequality
        if b + c > a:
            return [c, b, a]

    return [-1]


